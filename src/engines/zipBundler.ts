import JSZip from 'jszip';
import { saveAs } from 'file-saver';

export interface ZipBundleConfig {
  projectName: string;
  includeFrontend: boolean;
  includeBackend: boolean;
  includeDatabase: boolean;
  includeAIBlueprint: boolean;
  includeEnterprise: boolean;
}

export async function buildZip(config: ZipBundleConfig) {
  const zip = new JSZip();
  
  zip.file('README.md', generateReadme(config));
  zip.file('CARA-DEPLOY-CEPAT.md', generateDeployGuide());
  
  if (config.includeFrontend) {
    const folder = zip.folder('frontend')!;
    folder.file('App.tsx', '// Frontend generated by Free Web Builder');
    folder.file('index.html', '<!DOCTYPE html><html><head></head><body></body></html>');
    folder.file('package.json', '{"name":"frontend","type":"module"}');
  }
  
  if (config.includeBackend) {
    const folder = zip.folder('backend')!;
    folder.file('server.js', 'const express = require("express"); const app = express(); app.listen(3000);');
    folder.file('package.json', '{"name":"backend"}');
  }
  
  if (config.includeDatabase) {
    const folder = zip.folder('database')!;
    folder.file('database_full.sql', '-- SQL Database Generated by Free Web Builder\nCREATE TABLE users (id INT PRIMARY KEY);');
  }
  
  if (config.includeAIBlueprint) {
    zip.file('ai-blueprint/PRD.md', '# Project Requirements');
    zip.file('ai-blueprint/DESIGN.md', '# Design Rules - Anti AI Slop');
    zip.file('ai-blueprint/SECURITY.md', '# Security Policy');
    zip.file('ai-blueprint/TASKS.md', '# Task List');
  }
  
  if (config.includeEnterprise) {
    zip.file('enterprise-widget/widget.js', 'class Widget extends HTMLElement {}');
    zip.file('enterprise-widget/design-tokens.json', JSON.stringify({ colors: { primary: '#0ea5e9' } }));
  }
  
  const content = await zip.generateAsync({ type: 'blob' });
  saveAs(content, `${config.projectName || 'free-web-builder'}.zip`);
}

function generateReadme(cfg: ZipBundleConfig): string {
  return `# ${cfg.projectName || 'Free Web Builder Project'}

Dibuat dengan cinta oleh pengembang Indonesia.

Dukung karya lokal: https://saweria.co/
QR Code lokal tersedia di ./qr-saweria/qr-saweria.png
`;
}

function generateDeployGuide(): string {
  return `# CARA DEPLOY CEPAT — Anti-Ribet!

## Vercel (Gratis) — 2 Menit
1. Buka vercel.com
2. Login dengan GitHub
3. Import repo / upload folder .zip
4. Klik Deploy — Selesai!

## Netlify (Gratis) — 2 Menit
1. Drag folder build/ ke Netlify Drop
2. URL langsung aktif

## Supabase Database — 3 Menit
1. Buka supabase.com
2. SQL Editor → Paste database_full.sql
3. Klik Run → Seluruh tabel jadi!`;
}